def _enable_rls() -> None:
    """RLS：`USING`/`WITH CHECK` 都用同一租户谓词；未设置时 fail-closed（0 行）。

    `summary_rule` 额外放行系统内置规则（`user_id IS NULL`）。
    不启用 FORCE ROW LEVEL SECURITY：迁移/seed 以 owner 身份写入系统行，
    应用角色 `stock_app` 非 owner，策略照常生效。
    """
    for table in RLS_TABLES:
        predicate = TENANT_PREDICATE
        if table == "summary_rule":
            predicate = f"(user_id IS NULL OR {TENANT_PREDICATE})"
        op.execute(f"ALTER TABLE ledger.{table} ENABLE ROW LEVEL SECURITY")
        op.execute(
            f"CREATE POLICY tenant_isolation ON ledger.{table} "
            f"USING ({predicate}) WITH CHECK ({predicate})"
        )


def _grant_to_app() -> None:
    """运行时角色只给 DML；备份角色只给 SELECT（Architecture §9.1）。"""
    for schema in OWNED_SCHEMAS:
        op.execute(f"GRANT USAGE ON SCHEMA {schema} TO stock_app, stock_backup")
        op.execute(
            f"GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA {schema} TO stock_app"
        )
        op.execute(f"GRANT SELECT ON ALL TABLES IN SCHEMA {schema} TO stock_backup")
        op.execute(f"GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA {schema} TO stock_app")
        op.execute(
            f"ALTER DEFAULT PRIVILEGES IN SCHEMA {schema} "
            "GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO stock_app"
        )
        op.execute(
            f"ALTER DEFAULT PRIVILEGES IN SCHEMA {schema} "
            "GRANT USAGE, SELECT ON SEQUENCES TO stock_app"
        )


